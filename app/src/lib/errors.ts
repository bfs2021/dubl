/**
 * Человеческие тексты вместо сырых ответов сервера и ffmpeg.
 * Правило: что случилось своими словами + что делать дальше. Идемпотентно (уже понятный текст не трогаем).
 */
const RULES: [RegExp, string][] = [
  [/^Ошибка движка \((404|405)\)/, "Этого действия нет в движке — похоже, он старой версии. Перезапусти программу."],
  [/^Ошибка движка \(5\d\d\)/, "В движке что-то сломалось. Повтори; если не помогло — перезапусти программу."],
  [/^Not Found$|^Method Not Allowed$|\b404\b.*Not Found/i, "Этого действия нет в движке — похоже, он старой версии. Перезапусти программу."],
  [/moov atom not found|Invalid data found when processing input|Error opening input|could not find codec/i,
    "Файл повреждён или это не видео — программа не смогла его прочитать. Попробуй другой файл или перекодируй его."],
  [/No such file or directory|Файл не найден: file:/i, "Не нашёл файл по этому пути. Проверь путь или выбери файл заново."],
  [/Permission denied|Operation not permitted/i, "Нет доступа к файлу. Разреши программе читать эту папку в настройках macOS («Конфиденциальность → Файлы и папки»)."],
  [/No space left on device/i, "На диске не осталось места. Освободи немного и повтори."],
  [/ffmpeg|ffprobe/i, "Не получилось обработать видео или звук. Повтори; если снова не выйдет — попробуй другой файл."],
  [/Internal Server Error|Внутренняя ошибка/i, "В движке что-то сломалось. Повтори; если не помогло — перезапусти программу."],
  [/Bad Gateway|Service Unavailable|Gateway Timeout/i, "Движок не отвечает. Подожди пару секунд и повтори."],
  [/Failed to fetch|NetworkError|Load failed/i, "Движок не отвечает. Проверь, что он запущен, и повтори."],
];

export function humanizeError(msg: string): string {
  const m = (msg || "").trim();
  if (!m) return "Что-то пошло не так. Повтори.";
  // наши собственные тексты про коды ответа
  for (const [re, text] of RULES.slice(0, 2)) if (re.test(m)) return text;
  // движок по контракту отвечает {detail} по-русски — это уже человеческий текст
  if (/[А-Яа-яЁё]/.test(m) && !/Traceback|\.py\b/.test(m)) return m.length > 300 ? m.slice(0, 297) + "…" : m;
  for (const [re, text] of RULES) if (re.test(m)) return text;
  // длинные технические хвосты (пути, трейсы) не показываем
  if (/Traceback|\.py\b|\bat \w+\.\w+\(/.test(m) || m.length > 220) return "Что-то пошло не так внутри программы. Повтори; если повторится — перезапусти её.";
  return m;
}

/** ИИ не настроен — это не сбой, а подсказка идти в настройки. */
export const isNoAiError = (msg: string) => /ИИ для этой задачи не настроен|не настроен.*модел|Подключите модель/i.test(msg);
